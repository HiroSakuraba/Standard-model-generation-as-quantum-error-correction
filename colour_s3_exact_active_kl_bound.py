K=4
EIGENVALUES=(sp.Integer(0),sp.Integer(1))
GENERATOR_NAMES=("A","B","S")
EXPECTED_SUBGROUPS={
    "none":(1,9),
    "A":(2,6),
    "B":(2,6),
    "S":(2,5),
    "AB":(4,4),
    "AS":(6,2),
    "BS":(6,2),
    "ABS":(24,1),
}

# Five partitions of four, indexed by cycle partition.
CHARACTERS={
    "trivial":{(1,1,1,1):1,(2,1,1):1,(2,2):1,(3,1):1,(4,):1},
    "sign":{(1,1,1,1):1,(2,1,1):-1,(2,2):1,(3,1):1,(4,):-1},
    "standard_3":{(1,1,1,1):3,(2,1,1):1,(2,2):-1,(3,1):0,(4,):-1},
    "sign_twist_3":{(1,1,1,1):3,(2,1,1):-1,(2,2):-1,(3,1):0,(4,):1},
    "partition_22_2":{(1,1,1,1):2,(2,1,1):0,(2,2):2,(3,1):-1,(4,):0},
}


def cycle_type(p):
    """Exact conjugacy-class label of one permutation of four sites."""
    seen=set()
    sizes=[]
    for initial in range(4):
        if initial in seen:continue
        current=initial
        size=0
        while current not in seen:
            seen.add(current)
            size+=1
            current=p[current]
        sizes.append(size)
    return tuple(sorted(sizes,reverse=True))


def integer_permutation_rep(action):
    """Matrix with column j mapped to row action[j]."""
    if sorted(action)!=list(range(DGAUSS)):
        raise ValueError("Invalid 14-point group action")
    M=sp.zeros(DGAUSS)
    for j,i in enumerate(action):
        M[i,j]=1
    return M


def all_S4_character_projectors():
    """Exact central idempotents and irrep multiplicities, no SVD."""
    colour_orbits,lookup,_=four_colour_orbits()
    actions=positional_s4(colour_orbits,lookup)
    positions=tuple(permutations(range(4)))
    assert len(actions)==len(positions)==24
    rep=[integer_permutation_rep(g) for g in actions]
    projectors={}
    certificate={}
    total=sp.zeros(DGAUSS)
    for label,chars in CHARACTERS.items():
        degree=chars[(1,1,1,1)]
        P=sp.zeros(DGAUSS)
        for perm,mat in zip(positions,rep):
            P+=sp.Rational(degree*chars[cycle_type(perm)],24)*mat
        assert P*P==P
        rank=int(sp.trace(P))
        assert rank%degree==0
        multiplicity=rank//degree
        projectors[label]=P
        certificate[label]={
            "irrep_degree":degree,
            "multiplicity":multiplicity,
            "isotypic_physical_dimension":rank,
            "exact_projector_idempotent":True,
        }
        total+=P
    assert total==sp.eye(DGAUSS)
    for a,P in projectors.items():
        for b,Q in projectors.items():
            if a!=b:assert P*Q==sp.zeros(DGAUSS)
    expected={
        "trivial":(1,4,4),
        "sign":(1,0,0),
        "standard_3":(3,2,6),
        "sign_twist_3":(3,0,0),
        "partition_22_2":(2,2,4),
    }
    for name,(degree,m,r) in expected.items():
        check=certificate[name]
        assert (check["irrep_degree"],check["multiplicity"],
                check["isotypic_physical_dimension"])==(degree,m,r)
    return projectors,certificate


def exact_electric_split_on_unique_swap_code(P,E):
    """Exact 4D eigenspectrum via characteristic polynomial of PEP.

    PEP on entire 14D space has ten extra ZERO eigenvalues; the
    characteristic polynomial is t^11 (t-1)(t-1/3)(t-2/3).
    Its restriction to Ran P therefore has eigenvalues 0,1/3,2/3,1.
    """
    assert P*P==P and sp.trace(P)==K
    assert E*E==E
    projected=P*E*P
    x=sp.Symbol("lambda")
    characteristic=sp.factor(projected.charpoly(x).as_expr())
    expected=x**11*(x-1)*(3*x-1)*(3*x-2)/9
    assert sp.expand(characteristic-expected)==0
    assert projected!=sp.trace(projected)/K*P
    return {
        "compressed_electric_eigenvalues":[
            "0","1/3","2/3","1"
        ],
        "electric_is_scalar_on_unique_four_state_swap_sector":False,
        "characteristic_polynomial_full14":str(characteristic),
        "complete_24_swaps_plus_electric_perfect_KL_four_state_code":False,
    }


def generator_actions(ops):
    """Represent the three colour-swaps as integer permutations."""
    names=dict(zip(GENERATOR_NAMES,ops[:3]))
    result={}
    for name,M in names.items():
        permutation=[]
        for j in range(DGAUSS):
            nz=[i for i in range(DGAUSS) if M[i,j]!=0]
            assert len(nz)==1 and M[nz[0],j]==1
            permutation.append(nz[0])
        result[name]=tuple(permutation)
    return result


def generated_group_order(actions):
    """Finite exact closure under generators as permutations on 14 orbits."""
    ident=tuple(range(DGAUSS))
    discovered={ident}
    todo=[ident]
    index=0
    while index<len(todo):
        x=todo[index]
        index+=1
        for g in actions:
            y=tuple(g[x[j]] for j in range(DGAUSS))
            if y not in discovered:
                discovered.add(y)
                todo.append(y)
    return len(discovered)


def common_eigenspace_dimension(ops,signs,electric,electric_eigen):
    """Exact joint eigenspace rank; no numerical eigensolver."""
    constraints=[O-sign*sp.eye(DGAUSS)
                 for O,sign in zip(ops,signs)]
    constraints.append(electric-electric_eigen*sp.eye(DGAUSS))
    return DGAUSS-sp.Matrix.vstack(*constraints).rank()


def classify_electric_subgroups(ops):
    """All eight subsets of A,B,S; group-1D reps jointly with E.

    On a passive subspace, every subgroup operation is a SCALAR.
    Involutory generators then have eigenvalues ±1, E eigenvalue 0
    or 1 (R=I-2E). Enumerating every assignment is EXHAUSTIVE for
    decoherence-free subspaces of these particular generator families.

    This does not classify noiseless *subsystems* or active KL codes.
    """
    A,B,S,E=ops
    actions=generator_actions(ops)
    rows=[]
    for length in range(4):
        for subset in combinations(GENERATOR_NAMES,length):
            label="".join(subset) if subset else "none"
            generators=[dict(zip(GENERATOR_NAMES,ops[:3]))[s]
                        for s in subset]
            group_order=generated_group_order([actions[s] for s in subset])
            channels=[]
            for signs in product((1,-1),repeat=length):
                for eig in EIGENVALUES:
                    dim=common_eigenspace_dimension(generators,signs,E,eig)
                    if dim:
                        channels.append({
                            "generator_signs":dict(zip(subset,signs)),
                            "electric_projector_eigenvalue":int(eig),
                            "common_DFS_dimension":int(dim)
                        })
            best=max((v["common_DFS_dimension"] for v in channels),default=0)
            assert (group_order,best)==EXPECTED_SUBGROUPS[label],label
            rows.append({
                "generator_subset":label,
                "whole_generated_exchange_group_order":group_order,
                "max_passive_common_eigenspace_dimension":best,
                "passive_four_state_DFS_exists":best>=K,
                "nonzero_joint_scalar_subspaces":channels,
                "active_four_state_KL_status":"not resolved by passive eigenspace census",
            })
    assert len(rows)==8
    return rows


def full_group_active_KL_no_go(multiplicities,electric):
    """Finite-dimensional algebraic proof, stronger than commutant no-go.

    The error set is {rho(g): g in S4} union {R}. KL with I and each
    group element requires C†X C=scalar(X)I4 for every X in span rho(S4).
    In each irreducible block, X includes |a><b| tensor I_m.

    Writing the encoded isometry component corresponding to a fixed
    irrep index a as V_a : C^4 -> C^m, KL gives V_a†V_a=c_aa I4.
    For c_aa>0, rank V_a=4, requiring m>=4. Thus a 4D code cannot
    have support on irreps with m<4. The ONLY irrep with m>=4 is
    the trivial representation, with m=4, so any KL code must span
    that entire unique 4D space.

    R=I-2E is not scalar on the entire 4D space by the exact
    rational characteristic polynomial. The cross KL condition with
    identity therefore fails: no four-dimensional code can correct
    this complete 25-unitary Kraus set.

    This argument requires ALL 24 swaps to be among the errors,
    not just three swaps as a generating list of Hamiltonians.
    """
    eligible=[name for name,r in multiplicities.items()
              if r["multiplicity"]>=K]
    assert eligible==["trivial"]
    assert not electric[
        "electric_is_scalar_on_unique_four_state_swap_sector"]
    return {
        "number_distinct_allowed_swap_kraus_operators":24,
        "additional_electric_phase_kraus_operator":"R=I-2E",
        "group_representation_irrep_multiplicity_lower_bound_for_four_state_KL":4,
        "irrep_blocks_permitting_rank4_map_from_logical_space":eligible,
        "only_possible_four_state_all_swap_correcting_sector":
            "unique 4D trivial S4 representation",
        "electric_R_fails_cross_KL_identity_on_that_sector":True,
        "perfect_four_state_KL_for_full_25_operator_set_exists":False,
        "exact_proof":True,
        "important_distinction":"Does not rule out active 4D correction for {I,A,B,S,R} with only THREE swap-generator Kraus operations, nor for proper subgroup fault sets.",
    }


