"""Exact SU(2) bridge-error geometry certificates (4+4 co-located spins).

For two individually singlet spin-four registers, test Knill--Laflamme
against one fault chosen from a graph of cross-register Heisenberg exchanges.
Treat span{I, h_ab for edge ab in graph} as the error space. This is NOT the
full algebra generated by all the h_ab, nor a circuit-level recovery.

Run: python su2_bridge_error_geometry.py ; requires sympy and
su2_error_algebra_capacity.py in the same directory.
"""
from itertools import product
import sympy as sp

from su2_error_algebra_capacity import (
    I2, I4, four_spin_code, tensor, projected, h,
    singlet_exchange_representation, commutant_dimension,
)

A_BASIS = four_spin_code()
FULL_CODE = tuple(tensor(a, b) for a in A_BASIS for b in A_BASIS)
SITES_A = tuple(range(4))
SITES_D = tuple(range(4, 8))


def S(i, j):
    """Exact 2x2 singlet compression of the on-block dot product S_i.S_j."""
    if i == j:
        return sp.Rational(3, 4) * I2
    return projected(A_BASIS, lambda state: h(state, i, j))


def pauli_single_spin(state, spin, axis):
    """Act with exact Pauli I/X/Y/Z on a chosen physical spin half."""
    result = {}
    for bits, amplitude in state.items():
        target = list(bits)
        if axis in ("X", "Y"):
            target[spin] = 1 - target[spin]
        phase = {"I": 1, "X": 1,
                 "Y": sp.I if bits[spin] == 0 else -sp.I,
                 "Z": 1 if bits[spin] == 0 else -1}[axis]
        key = tuple(target)
        result[key] = result.get(key, 0) + phase * amplitude
    return result


def bridge_gram(e, f):
    """4x4 projected h_e^dagger h_f; e/f are across-block edges."""
    a, b = e
    c, d = f
    assert a in SITES_A and c in SITES_A
    assert b in SITES_D and d in SITES_D
    # Spin-zero Wigner-Eckart identity:
    # P0 S_i^mu S_j^nu P0 = (delta_mu_nu/3) P0 (S_i dot S_j) P0.
    return sp.kronecker_product(S(a, c), S(b - 4, d - 4)) / 3


def bridge_direct_gram(e, f):
    return projected(FULL_CODE, lambda psi: h(h(psi, *f), *e))


def code_from_indices(indices):
    return sp.eye(4)[:, list(indices)]


def kl_report(edges, embedding):
    """Check K^dagger E_i^dagger E_j K=c_ij I for all fault pairs."""
    k = embedding.cols
    gram = sp.zeros(len(edges) + 1)
    for a in range(len(edges) + 1):
        for b in range(len(edges) + 1):
            if a == b == 0:
                projected_overlap = I4
            elif a == 0 or b == 0:
                # Every cross-block spin exchange has zero first-order
                # singlet-product matrix element.
                projected_overlap = sp.zeros(4)
            else:
                projected_overlap = bridge_gram(edges[a - 1], edges[b - 1])
            M = sp.simplify(embedding.T.conjugate() * projected_overlap * embedding)
            if M != M[0, 0] * sp.eye(k):
                return False, (a, b, M)
            gram[a, b] = M[0, 0]
    assert gram == gram.T.conjugate()
    assert gram.is_positive_semidefinite
    return True, gram


def operator_span_rank(matrices):
    cols = [sp.Matrix(16, 1, list(m)) for m in matrices]
    return sp.Matrix.hstack(*cols).rank()


def graph_operator_system(edges):
    return [I4] + [bridge_gram(e, f) for e in edges for f in edges]


def exact_tests():
    assert projected(FULL_CODE, lambda psi: psi) == I4
    for i in range(4):
        assert S(i, i) == sp.Rational(3, 4) * I2
    for e, f in [((0, 4), (0, 4)), ((0, 4), (0, 5)),
                 ((0, 4), (1, 4)), ((0, 4), (1, 5)),
                 ((1, 5), (0, 4))]:
        assert sp.simplify(bridge_gram(e, f) - bridge_direct_gram(e, f)) == sp.zeros(4)
    print("Five independent microscopic 256-state versus SU(2) tensor-contraction bridge Gram checks PASS")

    one = ((0, 4),)
    full = sp.eye(4)
    good, gram = kl_report(one, full)
    assert good and gram == sp.diag(1, sp.Rational(3, 16))
    print("1 bridge: full 4D singlet-product code corrects span{I,h04}")

    two_match = ((0, 4), (1, 5))
    good, issue = kl_report(two_match, full)
    assert not good
    # Exact 2D code in the degenerate eigenspace of the mixed Gram.
    parity_code = code_from_indices((1, 2))
    good, gram = kl_report(two_match, parity_code)
    assert good and gram == sp.Matrix([
        [1, 0, 0], [0, sp.Rational(3, 16), -sp.Rational(1, 16)],
        [0, -sp.Rational(1, 16), sp.Rational(3, 16)]])
    # A rank-three scalar compression would require the second and
    # third ordered eigenvalues of Ph04 h15P to coincide (interlacing).
    eigs = sorted([sp.Rational(-1, 16)] * 2 + [sp.Rational(1, 48), sp.Rational(3, 16)])
    assert eigs[1] < eigs[2]
    print("2 disjoint bridges: full 4D fails; 2D odd-parity exact code PASS; k<=2 within product singlets")

    star = tuple((0, j) for j in SITES_D)
    frozen_d = code_from_indices((0, 2))
    good, gram_star = kl_report(star, frozen_d)
    assert good and gram_star.shape == (5, 5)
    assert operator_span_rank(graph_operator_system(star)) == 3
    # Stronger than single faults: ALL products of these star exchanges
    # act only on physical spin A0 plus D. Single-spin erasure from A
    # is correctable because P_A sigma(A0) P_A is scalar for all Pauli.
    for axis in ("I", "X", "Y", "Z"):
        expected = I2 if axis == "I" else sp.zeros(2)
        assert projected(A_BASIS, lambda psi, axis=axis:
                         pauli_single_spin(psi, 0, axis)) == expected
    # The star has a nondegenerate I_A tensor S_D(0,1); no k=3
    # scalar compression (Cauchy interlacing).
    assert sorted(S(0, 1).eigenvals().keys()) == [
        -sp.Rational(3, 4), sp.Rational(1, 4)]
    good, _ = kl_report(star + ((1, 4),), frozen_d)
    assert not good
    print("4-bridge star: k=2 maximum; stronger exact erasure protection against arbitrary operators on physical A0+D")
    print("Adding one nonstar bridge (1,4) breaks the protected A logical qubit")

    # 3-edge L: pairwise Grams span I, A⊗I, I⊗B, A⊗B.
    # Their linear span contains four rank-one spectral projectors.
    # Rank(K†R K)<=1 for each rank-one R forces all four scalar
    # KL coefficients to vanish if k>=2, contradicting sum R=I4.
    ell = ((0, 4), (0, 5), (1, 4))
    ops = graph_operator_system(ell)
    assert operator_span_rank(ops) == 4
    assert S(0, 1) == -I2 / 4 - sp.diag(1, -1) / 2
    z0 = sp.diag(1, 0)
    z1 = sp.diag(0, 1)
    projectors = [sp.kronecker_product(a, b) for a, b in product((z0, z1), repeat=2)]
    assert sum(projectors, sp.zeros(4)) == I4
    for r in projectors:
        assert r.rank() == 1
        assert operator_span_rank(ops + [r]) == 4
    print("3-bridge L-shape: all four rank-one product projectors in KL operator system; no k>=2 subcode within 4D")

    square = ((0, 4), (0, 5), (1, 4), (1, 5))
    assert operator_span_rank(graph_operator_system(square)) == 4
    assert operator_span_rank(graph_operator_system(tuple(
        (a, b) for a in SITES_A for b in SITES_D))) == 9
    print("4-bridge plaquette KL operator-system rank 4; complete K4,4 rank 9; both include L no-go")

    # Full 14D global-singlet error algebras differ from the 4D host.
    swap = singlet_exchange_representation(8)
    connected_4 = (0, 1, 4, 5)
    C4 = sum((swap(i, j) for idx, i in enumerate(connected_4)
              for j in connected_4[idx + 1:]), sp.zeros(14))
    assert [14 - (C4 - j * (j + 1) * sp.eye(14)).rank()
            for j in (0, 1, 2)] == [4, 9, 1]
    assert commutant_dimension([swap(*edge) for edge in ell]) == 14
    # L's algebra M2⊗I2 + M3⊗I3 + C has commutant dimension 14.
    assert commutant_dimension([swap(*edge) for edge in star]) == 5
    connected_5 = (0, 4, 5, 6, 7)
    C5 = sum((swap(i, j) for idx, i in enumerate(connected_5)
              for j in connected_5[idx + 1:]), sp.zeros(14))
    C5 += (-sp.Rational(5, 4)) * sp.eye(14)
    assert [14 - (C5 - j * (j + 1) * sp.eye(14)).rank()
            for j in (sp.Rational(1, 2), sp.Rational(3, 2))] == [10, 4]
    # Star algebra M5⊗I2 + M4 has commutant dimension 5.
    connected_all = [(i, i + 1) for i in range(7)]
    assert commutant_dimension([swap(*edge) for edge in connected_all]) == 1
    print("14D global-singlet L graph: 4+9+1 spin sectors, commutant dimension 14; noiseless qutrit available")
    print("14D global-singlet star: 10+4 spin sectors, commutant dimension 5; noiseless qubit available")
    print("14D global-singlet connected graph: full M14, commutant dimension 1; no noiseless subsystem")
    print("ALL EXACT GEOMETRY-RESTRICTED KL TESTS PASSED")


if __name__ == "__main__":
    exact_tests()
