"""Exact four-logical-state ACTIVE error-correction bound for finite S3 gauge model.

Previous exact commutant rank-6 result showed no FOUR-dimensional
NOISELESS SUBSYSTEM for the *algebra* of all gauge-dressed matter swaps
and link-electric E. That alone did NOT exclude an actively corrected
code. Here we give a strictly stronger theorem, for a clearly defined
finite Kraus error SET:

  F = {all 24 gauge-covariant matter permutations} union {R=I-2E}.

Knill–Laflamme for every permutation g,h and R implies that for all
X in the COMPLEX GROUP ALGEBRA of S4, K†XK = scalar(X) I_4.

Exact character projectors give the representation decomposition of
the 14-dimensional physical S3 Gauss space, as an S4 module:
   4 copies of trivial dimension-1    => 4 physical dimensions
   2 copies of irrep [2,2] dimension-2 => 4 physical dimensions
   2 copies of irrep [3,1] dimension-3 => 6 physical dimensions
   no sign or sign-twisted 3D irreps.

For each irrep lambda, a 4D isometry K into the full physical space
has components V_{lambda,a}: C^4 -> C^{m_lambda}, one per irrep index a.
KL for the group algebra's matrix units says
V_{lambda,a}† V_{lambda,b}=c_{lambda,a,b} I_4.
If any V_{lambda,a} is nonzero, c_{lambda,a,a}>0, and V is an
injective rank-4 map into the multiplicity space C^{m_lambda}.
THEREFORE m_lambda>=4. Only the trivial irrep has multiplicity4,
so every 4D code correcting all 24 swaps must occupy precisely the
unique four-dimensional S4-fixed subspace.

But the electric projector, compressed onto that S4-fixed subspace,
has EXACT eigenvalues 0,1/3,2/3,1, hence electric R=I-2E is
non-scalar there. KL for the pair {I,R} fails. Thus there is NO
4D PERFECT ACTIVE CODE for this *specified 25-error Kraus set*.

For smaller Kraus sets, the theorem DOES NOT automatically apply:
having only the three GENERATOR swaps and R is different from including
all 24 permutations individually as Kraus operators.

Enumerate exact common 1D-representation/electric-eigenspace
dimensions for every one of the eight subgroups generated by subsets
of the three primitive swaps, plus the same electric link error.
A four-dimensional passive subspace exists for the empty, single-swap
and commuting two-swap subgroups, but not for the two order-six S3
subgroups or full order-24 S4. Active correction in those proper
subgroups is NOT decided here.

All spectral and multiplicity ranks are exact SymPy RATIONAL arithmetic.
No native full SU3 link, hardware error rates or nine-quark 21D code.
"""
