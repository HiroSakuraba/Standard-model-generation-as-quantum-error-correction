#!/usr/bin/env python3
"""Full Standard Model centre echo: the Z6 that every SM field ignores (see SM_CENTER_ECHO.md).

The cubic-Casimir echo of su3_cubic_casimir_echo.py multiplies every SU(3) link
raising operator by omega = exp(2 pi i/3).  Here the same idea is extended to the
whole gauge group SU(3) x SU(2) x U(1)_Y.  A link of a lattice gauge theory carries an
irrep R; the centre Z3 x Z2 x U(1) acts on R by a scalar (Schur), labelled by
    t = triality of the SU(3) irrep   (mod 3)
    d = N-ality of the SU(2) irrep    (mod 2)
    n = 6Y, hypercharge flux in units of 1/6 (integer)
A centre pulse is the diagonal link unitary  P(a,b,theta) = omega^(a t) (-1)^(b d) e^(i theta n).
Any term that changes the link class by (dt,dd,dn) is multiplied by the same character,
so averaging over a group of pulses keeps exactly the terms whose character is trivial.

Checks (exact integer / rational arithmetic, plus a small numerical echo):
 1. every SM field obeys 6Y = 3d - 2t (mod 6), the Z6 relation;
 2. the centre elements transparent to every SM field form exactly Z6; the quark doublet Q
    alone already fixes it, and the other five fields (and the Higgs) are transparent;
 3. echo table: which pulse groups keep which hopping, Yukawa and Wilson terms;
 4. nu^c is the only field no centre pulse can touch;
 5. Z6 stabilizer = exp(2 pi i (Q_em + t/3)): SM states have eigenvalue 1, so the syndrome
    of the Z6 echo is a fractionally charged colour singlet (or an unaccompanied flux);
 6. a weight pattern on a periodic lattice gives every plaquette a non-trivial Z6 phase
    while every matter hop stays transparent (2D and 3D, all plaquettes enumerated);
 7. the pulses are functions of the link Casimirs (SU(3): (C2,C3) separate all irreps with
    p+q <= 8; the cubic-Casimir formula of the qutrit chain fails at (2,0));
 8. numerical toggling-frame echo on one truncated link register: the 6-pulse Z6 cycle
    converges to the matter-only Hamiltonian, with error falling as 1/cycles.
Requires numpy and scipy.  Ends with ALL SM CENTRE-ECHO CHECKS PASSED.
"""
from fractions import Fraction as F
import itertools
import numpy as np
from scipy.linalg import expm

# name: (SU(3) irrep (p,q), SU(2) dim, Y)   Q = T3 + Y convention, left-handed Weyl fields
FIELDS = {
    'Q':   ((1, 0), 2, F(1, 6)),
    'u^c': ((0, 1), 1, F(-2, 3)),
    'd^c': ((0, 1), 1, F(1, 3)),
    'L':   ((0, 0), 2, F(-1, 2)),
    'e^c': ((0, 0), 1, F(1)),
    'nu^c': ((0, 0), 1, F(0)),
}
HIGGS = {'H': ((0, 0), 2, F(1, 2))}
ALL = {**FIELDS, **HIGGS}


def labels(field):
    (p, q), dim2, Y = ALL[field]
    n = 6 * Y
    assert n.denominator == 1
    return (p - q) % 3, (dim2 - 1) % 2, int(n)


def character(lab, a, b, theta_over_2pi):
    """Phase of centre element (omega^a, (-1)^b, e^{2 pi i theta}) on link class lab, as a fraction mod 1."""
    t, d, n = lab
    return (F(a * t, 3) + F(b * d, 2) + theta_over_2pi * n) % 1


def check_z6_relation():
    rows = []
    for f in ALL:
        t, d, n = labels(f)
        assert (n - (3 * d - 2 * t)) % 6 == 0, f
        rows.append((f, t, d, n))
    print('field  t  d  6Y   (6Y - 3d + 2t) mod 6')
    for f, t, d, n in rows:
        print(f'{f:5s} {t:2d} {d:2d} {n:3d}   {(n - 3 * d + 2 * t) % 6}')
    return rows


def transparent_group(fields):
    """All centre elements (a,b,theta) transparent to the given fields.

    Q (n=1) forces e^{2 pi i theta} = omega^{-a}(-1)^{-b}; so theta ranges over a finite set once a
    field with n = +-1 is present.  For field sets without such a field we sample theta on a fine
    rational grid, which is enough to show the group is larger than Z6.
    """
    grid = [F(k, 36) for k in range(36)]
    sols = []
    for a in range(3):
        for b in range(2):
            for th in grid:
                if all(character(labels(f), a, b, th) == 0 for f in fields):
                    sols.append((a, b, th))
    return sols


def check_transparent():
    full = transparent_group(list(FIELDS) + ['H'])
    assert len(full) == 6
    gen = (1, 1, F(1, 6))
    gen_powers = {((k * gen[0]) % 3, (k * gen[1]) % 2, (k * gen[2]) % 1) for k in range(6)}
    assert set(full) == gen_powers
    print('centre elements transparent to all SM fields:', sorted(full), '= Z6 generated by', gen)
    assert set(transparent_group(['Q'])) == set(full)
    print('Q alone fixes the same Z6; u^c, d^c, L, e^c, nu^c, H are then transparent automatically')
    leptons = transparent_group(['L', 'e^c', 'nu^c', 'H'])
    assert len(leptons) > 6
    print(f'leptons + Higgs alone: {len(leptons)} transparent elements on the 3x2x36 grid (not just Z6)')
    return full


# ------------------------------------------------------------------- echo table
TERMS = {
    # name: change of link class (t, d, n) produced on the link it acts on
    'SU(3) Wilson, fundamental': (1, 0, 0),
    'SU(2) Wilson, fundamental': (0, 1, 0),
    'U(1) Wilson, n=1': (0, 0, 1),
    'U(1) Wilson, n=6': (0, 0, 6),
    **{f'hop {f}': labels(f) for f in ALL},
    'Yukawa (on-site)': (0, 0, 0),
    'electric energy (diagonal)': (0, 0, 0),
}
GROUPS = {
    'colour Z3': [(a, 0, F(0)) for a in range(3)],
    'weak Z2': [(0, b, F(0)) for b in range(2)],
    'hypercharge U(1)': [(0, 0, F(k, 36)) for k in range(36)],   # grid; |n|<36 so exact for these terms
    'SM Z6': [((k) % 3, k % 2, F(k, 6)) for k in range(6)],
    'full centre': [(a, b, F(k, 36)) for a in range(3) for b in range(2) for k in range(36)],
}


def survives(lab, group):
    return all(character(lab, *g) == 0 for g in group)


def check_echo_table():
    names = list(GROUPS)
    print('\nterm kept (K) or cancelled (.) by averaging over each pulse group')
    print(f'{"":28s}' + ''.join(f'{g:>18s}' for g in names))
    table = {}
    for term, lab in TERMS.items():
        row = [survives(lab, GROUPS[g]) for g in names]
        table[term] = row
        print(f'{term:28s}' + ''.join(f'{("K" if r else "."):>18s}' for r in row))
    z6 = names.index('SM Z6')
    for f in ALL:
        assert table[f'hop {f}'][z6], f
    for w in ('SU(3) Wilson, fundamental', 'SU(2) Wilson, fundamental', 'U(1) Wilson, n=1'):
        assert not table[w][z6]
    assert table['U(1) Wilson, n=6'][z6]
    c3 = names.index('colour Z3')
    assert [f for f in ALL if not table[f'hop {f}'][c3]] == ['Q', 'u^c', 'd^c']
    w2 = names.index('weak Z2')
    assert [f for f in ALL if not table[f'hop {f}'][w2]] == ['Q', 'L', 'H']
    u1 = names.index('hypercharge U(1)')
    assert [f for f in ALL if table[f'hop {f}'][u1]] == ['nu^c']
    full = names.index('full centre')
    assert [t for t in TERMS if table[t][full]] == ['hop nu^c', 'Yukawa (on-site)', 'electric energy (diagonal)']
    print('Z6 keeps every matter hop and kills every fundamental Wilson term;')
    print('the full centre kills everything that moves except nu^c.')
    return table


def check_integer_charge():
    """Z6 eigenvalue exp(2 pi i (Q_em + t/3)) on every weight of every SM field."""
    for f in ALL:
        (p, q), dim2, Y = ALL[f]
        t, d, n = labels(f)
        for twoT3 in range(-(dim2 - 1), dim2, 2):
            Qem = F(twoT3, 2) + Y
            # Z6 generator acts as omega^t (-1)^d e^{2 pi i Y}; equals exp(2 pi i (Q_em + t/3))
            assert (F(t, 3) + F(d, 2) + Y) % 1 == (Qem + F(t, 3)) % 1 == 0, (f, twoT3)
    # colour singlets have integer charge; triplets charge -t/3 mod 1
    print('Z6 stabilizer exp(2 pi i (Q_em + t/3)) = 1 on every weight of every SM field and the Higgs')
    # A detected error: a colour-singlet with charge 1/2, or a bare colour triplet with integer charge
    for bad in [(0, 0, 3), (1, 0, 0), (0, 1, 0)]:
        assert character(bad, 1, 1, F(1, 6)) != 0
    print('fractionally charged singlets (6Y=3, singlet) and bare SU(3)/SU(2) fluxes give syndrome != 1')


# ------------------------------------------------------------------- lattice weights
def lattice_weights(L, dim):
    """Links along axis mu get weight x_{mu-1} (cyclically); in 2D the x-links get weight 0."""
    sites = list(itertools.product(range(L), repeat=dim))

    def w(x, mu):
        if dim == 2 and mu == 0:
            return 0
        return x[(mu - 1) % dim]
    bad = 0
    count = 0
    for x in sites:
        for mu, nu in itertools.combinations(range(dim), 2):
            # oriented plaquette x -> x+mu -> x+mu+nu -> x+nu -> x
            xm = list(x); xm[mu] = (xm[mu] + 1) % L
            xn = list(x); xn[nu] = (xn[nu] + 1) % L
            W = w(x, mu) + w(tuple(xm), nu) - w(tuple(xn), mu) - w(x, nu)
            count += 1
            if W % 6 not in (1, 5):
                bad += 1
    return count, bad


def check_lattice():
    for dim in (2, 3):
        count, bad = lattice_weights(6, dim)
        assert bad == 0
        print(f'{dim}D periodic 6^{dim} lattice: all {count} plaquettes get oriented weight +-1 mod 6')
    # pulse on link l: exp(2 pi i k w_l e6(c_l)/6), e6 = 2t + 3d + n
    for f in ALL:
        t, d, n = labels(f)
        assert (2 * t + 3 * d + n) % 6 == 0
    for e6, name in ((2, 'SU(3)'), (3, 'SU(2)'), (1, 'U(1) n=1')):
        assert all((k * e6 * s) % 6 for k in (1,) for s in (1, 5))
        print(f'  fundamental {name} plaquette: Z6 class {e6}, phase exp(2 pi i {e6}/6 * (+-1)) != 1')
    print('  every matter hop: Z6 class 0 on its link, transparent for every weight pattern')


# ------------------------------------------------------------------- Casimirs
def check_casimirs():
    def C2(p, q):
        return F(p * p + q * q + p * q + 3 * p + 3 * q, 3)

    def C3(p, q):
        return F((p - q) * (2 * p + q + 3) * (p + 2 * q + 3), 18)
    irreps = [(p, q) for p in range(9) for q in range(9) if p + q <= 8]
    seen = {}
    for pq in irreps:
        key = (C2(*pq), C3(*pq))
        assert key not in seen, (pq, seen.get(key))
        seen[key] = pq
    print(f'SU(3): (C2, C3) separate all {len(irreps)} irreps with p+q <= 8, so omega^(p-q) is a function of the Casimirs')
    # the qutrit-chain formula omega^{(9/10) C3}
    for pq, ok in (((0, 0), True), ((1, 0), True), ((0, 1), True), ((2, 0), False), ((1, 1), True)):
        x = (F(9, 10) * C3(*pq) - (pq[0] - pq[1])) / 3
        assert (x.denominator == 1) == ok, pq
    print('  omega^{(9/10)C3} equals omega^t on 1, 3, 3bar, 8 but not on 6: the general pulse needs (C2,C3)')
    js = [F(k, 2) for k in range(0, 17)]
    assert len({j * (j + 1) for j in js}) == len(js)
    print('SU(2): C2 = j(j+1) separates all j <= 8, so (-1)^{2j} is a function of C2;  U(1): pulse is e^{i theta E}')


# ------------------------------------------------------------------- numerics
def check_numerical_echo():
    """One link register Z3 x Z2 x {n = -N..N}; hops shift the class, Wilson terms shift one factor."""
    N = 7
    ns = list(range(-N, N + 1))
    basis = [(t, d, n) for t in range(3) for d in range(2) for n in ns]
    pos = {b: i for i, b in enumerate(basis)}
    D = len(basis)

    def shift(delta):
        M = np.zeros((D, D), dtype=complex)
        for b in basis:
            c = ((b[0] + delta[0]) % 3, (b[1] + delta[1]) % 2, b[2] + delta[2])
            if c in pos:
                M[pos[c], pos[b]] = 1
        return M
    rng = np.random.default_rng(7)
    E = np.diag([0.3 * (b[0] != 0) + 0.2 * b[1] + 0.05 * b[2] ** 2 for b in basis]).astype(complex)
    Hm = sum(rng.uniform(0.5, 1.0) * (shift(labels(f)) + shift(labels(f)).conj().T) for f in FIELDS if f != 'nu^c')
    Hg = sum(rng.uniform(0.5, 1.0) * (shift(dl) + shift(dl).conj().T) for dl in ((1, 0, 0), (0, 1, 0), (0, 0, 1)))
    H = E + Hm + Hg
    pulses = [np.diag([np.exp(2j * np.pi * k * (2 * b[0] + 3 * b[1] + b[2]) / 6) for b in basis]) for k in range(6)]
    Hbar = sum(P.conj().T @ H @ P for P in pulses) / 6
    assert np.allclose(Hbar, E + Hm, atol=1e-12)
    print('\nnumerical link register (D=%d): (1/6) sum_k P_k^dag H P_k = electric + matter hops, exactly' % D)
    T = 2.0
    target = expm(-1j * (E + Hm) * T)
    errs = []
    for cycles in (4, 16, 64):
        tau = T / (6 * cycles)
        step = expm(-1j * H * tau)
        cyc = np.eye(D, dtype=complex)
        for P in pulses:
            cyc = P.conj().T @ step @ P @ cyc
        U = np.linalg.matrix_power(cyc, cycles)
        errs.append(np.linalg.norm(U - target, 2))
        print(f'  {cycles:3d} Z6 cycles: ||U_echo - exp(-i H_matter T)|| = {errs[-1]:.3e}')
    assert errs[0] > errs[1] > errs[2] and errs[2] < 0.05
    ratio = errs[1] / errs[2]
    assert 3.0 < ratio < 5.0, ratio
    print(f'  error ratio per 4x cycles = {ratio:.2f} (first-order average-Hamiltonian scaling)')


def main():
    check_z6_relation()
    check_transparent()
    check_echo_table()
    assert all(x == 0 for x in labels('nu^c'))
    print('nu^c: class (0,0,0); every centre pulse and every link-diagonal unitary leaves its hop alone')
    check_integer_charge()
    check_lattice()
    check_casimirs()
    check_numerical_echo()
    print('ALL SM CENTRE-ECHO CHECKS PASSED')


if __name__ == '__main__':
    main()
